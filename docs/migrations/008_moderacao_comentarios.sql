-- Issue #216: área de moderação de comentários e contestações (RF10, decisões C06, C07 e C08).
-- Depende de: 001_initial_schema.sql (perfis), 002_comentarios.sql (comentarios),
--             005_denuncias_comentarios.sql (denuncias_comentarios).
-- Fora do escopo: filtro automático no envio (#214) e descarte após 90 dias (#217).
--
-- Todas as tabelas desta migração são privadas: sem políticas para anon/authenticated,
-- acesso exclusivo do backend via service_role. Nenhum usuário recebe papel de moderador
-- por padrão; a inclusão de integrantes da equipe é feita explicitamente em `moderadores`.

BEGIN;

-- 1. Papel de moderador (sem acesso por padrão para usuários comuns)
CREATE TABLE IF NOT EXISTS moderadores (
    usuario_id   UUID PRIMARY KEY REFERENCES perfis(id) ON DELETE CASCADE,
    concedido_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Histórico de decisões de moderação (toda ação registra quem decidiu e a justificativa)
CREATE TABLE IF NOT EXISTS moderacoes_comentarios (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comentario_id BIGINT NOT NULL REFERENCES comentarios(id) ON DELETE CASCADE,
    moderador_id  UUID   NOT NULL REFERENCES perfis(id)      ON DELETE CASCADE,
    acao          TEXT   NOT NULL,
    justificativa TEXT   NOT NULL,
    criado_em     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_moderacoes_acao CHECK (acao IN ('manter', 'ocultar', 'restaurar')),
    CONSTRAINT ck_moderacoes_justificativa_tamanho CHECK (
        char_length(regexp_replace(justificativa, '^[[:space:]]+|[[:space:]]+$', '', 'g'))
        BETWEEN 2 AND 1000
    )
);

CREATE INDEX IF NOT EXISTS idx_moderacoes_comentario_criado
    ON moderacoes_comentarios (comentario_id, criado_em DESC);

-- 3. Pedidos privados de revisão (contestação) enviados pelo autor do comentário
CREATE TABLE IF NOT EXISTS contestacoes_comentarios (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comentario_id BIGINT NOT NULL REFERENCES comentarios(id) ON DELETE CASCADE,
    usuario_id    UUID   NOT NULL REFERENCES perfis(id)      ON DELETE CASCADE,
    justificativa TEXT   NOT NULL,
    criado_em     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    resolvida_em  TIMESTAMPTZ,
    CONSTRAINT ck_contestacoes_justificativa_tamanho CHECK (
        char_length(regexp_replace(justificativa, '^[[:space:]]+|[[:space:]]+$', '', 'g'))
        BETWEEN 2 AND 1000
    )
);

-- Uma contestação em aberto por comentário por vez
CREATE UNIQUE INDEX IF NOT EXISTS uq_contestacoes_ativa_comentario
    ON contestacoes_comentarios (comentario_id)
    WHERE resolvida_em IS NULL;

CREATE INDEX IF NOT EXISTS idx_contestacoes_abertas
    ON contestacoes_comentarios (criado_em)
    WHERE resolvida_em IS NULL;

-- RLS privado: apenas service_role lê e grava estas tabelas
ALTER TABLE moderadores ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON moderadores FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, DELETE ON moderadores TO service_role;

ALTER TABLE moderacoes_comentarios ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON moderacoes_comentarios FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON moderacoes_comentarios TO service_role;

ALTER TABLE contestacoes_comentarios ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON contestacoes_comentarios FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON contestacoes_comentarios TO service_role;

COMMIT;